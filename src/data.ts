/** Таблица маршрутов: путь → что показывать */
export type Route = { kind: 'home' } | { kind: 'service'; service: Service } | { kind: 'article'; article: Article } | { kind: 'info'; page: InfoPage };
export function resolveRoute(path: string): Route | null {
  const p = rel(path).replace(/index\.html$/, '');
  if (p === '/' || p === '') return { kind: 'home' };
  const s = SERVICES.find(x => servicePath(x) === p);
  if (s) return { kind: 'service', service: s };
  const a = NEWS.find(x => articlePath(x) === p || articlePath(x) === p + '/');
  if (a) return { kind: 'article', article: a };
  const page = PAGES.find(x => x.path === p);
  if (page) return { kind: 'info', page };
  return null;
}
